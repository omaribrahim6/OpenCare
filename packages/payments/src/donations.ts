// Card donations (SPEC §8): a Nessie deposit into the fund account, recorded with core's
// `recordDonation` (idempotent per deposit ID) and a memo-only Solana receipt. No card details
// ever reach this code: it's mock banking, and the donor only picks an amount.

import { createHash, randomBytes } from "node:crypto";
import type { Donation } from "@abdulcare/contracts";
import { CoreError, MAX_DONATION_CENTS, recordDonation, setDonationReceipt } from "@abdulcare/core";
import { dollarsToCents } from "./money";
import type { NessieDeposit } from "./nessie";
import type { PaymentsDeps } from "./redeem";
import { explorerTxUrl, sendReceipt, verifySolDonation } from "./solana";

export const MIN_DONATION_CENTS = 100;

const KEY_PATTERN = /^[A-Za-z0-9_-]{8,64}$/;

export interface DonationReceipt {
  donation: Donation;
  depositId: string;
  explorerUrl: string | null;
  /** True when this idempotency key was already used: nothing new was deposited. */
  duplicate: boolean;
}

function donationMemo(key: string): string {
  return `ac_don_${createHash("sha256").update(key).digest("hex").slice(0, 20)}`;
}

/**
 * Donate by card. Pass the same `idempotencyKey` on a retry (e.g. generated by the form) and the
 * second call returns the first donation instead of depositing twice.
 */
export async function donateByCard(
  deps: PaymentsDeps,
  input: { amountCents: number; idempotencyKey?: string },
): Promise<DonationReceipt> {
  const { amountCents } = input;
  if (!Number.isInteger(amountCents) || amountCents < MIN_DONATION_CENTS || amountCents > MAX_DONATION_CENTS) {
    throw new CoreError("bad_request", "Donations must be between $1 and $10,000, in whole cents");
  }
  if (input.idempotencyKey !== undefined && !KEY_PATTERN.test(input.idempotencyKey)) {
    throw new CoreError("bad_request", "idempotencyKey must be 8–64 letters, digits, _ or -");
  }
  const key = input.idempotencyKey ?? randomBytes(12).toString("base64url");
  const description = `AbdulCare donation ${key}`;

  let deposit: NessieDeposit | undefined;
  if (input.idempotencyKey) {
    deposit = (await deps.nessie.listDeposits(deps.fundAccountId)).find((d) => d.description?.includes(key));
  }
  const duplicate = deposit !== undefined;
  deposit ??= await deps.nessie.createDeposit(deps.fundAccountId, { amountCents, description });

  // Safe to repeat: core records each deposit ID once.
  let donation = await recordDonation(deps.db, {
    rail: "nessie",
    amountCents: dollarsToCents(deposit.amount),
    nessieDepositId: deposit._id,
  });

  if (!donation.solanaSignature && deps.solana) {
    try {
      const { signature } = await sendReceipt(deps.solana, { memo: donationMemo(key), lamports: 0 });
      await setDonationReceipt(deps.db, donation.id, signature);
      donation = { ...donation, solanaSignature: signature };
    } catch (err) {
      deps.log?.(`donation receipt: ${(err as Error).message}`);
    }
  }

  return {
    donation,
    depositId: deposit._id,
    explorerUrl: donation.solanaSignature ? explorerTxUrl(donation.solanaSignature) : null,
    duplicate,
  };
}

/**
 * Record a devnet SOL donation the donor already sent to the treasury. `centsPerSol` is the
 * fund's fixed demo rate (devnet SOL has no real value). Each signature counts once.
 */
export async function recordSolDonation(
  deps: PaymentsDeps,
  input: { signature: string; centsPerSol: number },
): Promise<{ donation: Donation; lamports: number }> {
  if (!deps.solana) throw new CoreError("internal", "Solana is not configured");
  const found = await verifySolDonation(deps.solana, input.signature);
  if (!found) throw new CoreError("bad_request", "That signature isn't a confirmed transfer to the fund treasury");
  const amountCents = Math.round((found.lamports / 1e9) * input.centsPerSol);
  if (amountCents <= 0) throw new CoreError("bad_request", "That donation is too small to record");
  const donation = await recordDonation(deps.db, { rail: "solana", amountCents, solanaSignature: input.signature });
  return { donation, lamports: found.lamports };
}
